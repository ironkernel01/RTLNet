#!/usr/bin/env python3
"""
File: h264_gen_cbp_table.py
Purpose: derive the inter coded_block_pattern mapping of ITU-T Rec. H.264 Table 9-4 (ChromaArrayType 1 or 2, column
  Inter) from the JM 19.1 decoder source (ldecod/vlc.h, NCBP[1][codeNum][1]) and write
  (1) testbench/tb_h264_cbp_tab.svh: the forward table codeNum -> coded_block_pattern used by the benches, and
  (2) print the inverse function (coded_block_pattern -> codeNum) in the form used by rtlnet_h264_pkg.sv, so the RTL
      function can be checked against it (`--check` compares the function text of the package with the generated one).
Usage: python -I h264_gen_cbp_table.py [--jm <path to vlc.h>] [--check]
Revision: 11-10-2026
  * 11-10-2026: initial version (phase 2c-1).
"""
import argparse
import os
import re
import sys

DEFAULT_JM = os.environ.get("RTLNET_JM_SRC", "") 


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jm", default="")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    here = os.path.dirname(os.path.abspath(__file__))
    cand = [a.jm] if a.jm else []
    if DEFAULT_JM:
        cand.append(os.path.join(DEFAULT_JM, "source/app/ldecod/vlc.h"))
    cand.append(os.path.join(here, "tb_h264_cbp_tab.svh"))
    src = None
    for c in cand:
        if c.endswith("vlc.h") and os.path.exists(c):
            src = open(c).read()
            break
    if src is None:
        print("JM vlc.h not found (set RTLNET_JM_SRC or --jm); nothing generated")
        return 2
    m = re.search(r"static const byte NCBP\[2\]\[48\]\[2\]=\s*\{(.*?)\n\};", src, re.S)
    second = m.group(1).split("},\n  {")[1]
    pairs = re.findall(r"\{\s*(\d+),\s*(\d+)\}", second)
    inter = [int(b) for _, b in pairs]
    assert len(inter) == 48 and len(set(inter)) == 48
    inv = {c: i for i, c in enumerate(inter)}
    svh = ["// Generated by h264_gen_cbp_table.py from JM 19.1 ldecod/vlc.h NCBP[1][codeNum][1] (Table 9-4, inter column).",
           "localparam int CBP_INTER_BY_CODE [48] = '{" + ", ".join(str(v) for v in inter) + "};"]
    func = ["    case (cbp)"] + ["      6'd%d: r = 6'd%d;" % (c, inv[c]) for c in range(48)]
    if a.check:
        pkg = open(os.path.join(here, "../hdl/rtlnet_h264_pkg.sv")).read()
        ok = all(("6'd%d: r = 6'd%d;" % (c, inv[c])) in pkg for c in range(48))
        print("CBP TABLE CHECK:", "PASS" if ok else "FAIL")
        return 0 if ok else 1
    open(os.path.join(here, "tb_h264_cbp_tab.svh"), "w", newline="\n").write("\n".join(svh) + "\n")
    print("\n".join(func))
    return 0


if __name__ == "__main__":
    sys.exit(main())
