// -----------------------------------------------------------------------------
// File: tb_rtlnet_h264_cavlc.sv
// Purpose: self-checking bench of rtlnet_h264_cavlc_blk: the CAVLC residual block coder against a reference encoder
//   written in the bench from ITU-T Rec. H.264 clause 9.2 (tb_h264_cavlc_ref.svh).
// Overview:
//   * Each block runs through the DUT with random cmd_ready back-pressure; the concatenated command fields (cmd_val low
//     cmd_len bits, MSB first) must equal the reference bit string bit for bit, and total_coeff must equal the reference
//     count. Non-zero garbage above maxNumCoeff checks the input masking.
//   * Directed sets: every (nC class, TotalCoeff, TrailingOnes) combination for maxNumCoeff 16, 15 and the chroma DC
//     block (nC bands 0-1, 2-3, 4-7, >= 8 and nC = -1), every (TotalCoeff, total_zeros) pair, every (zerosLeft, run_before)
//     pair, a sweep of every single level from -2047 to +2047 (and as first level of an 11-coefficient block, where
//     suffixLength starts at 1), then random blocks of random density and magnitude (levels up to 2047, so suffixLength
//     reaches 6 and the prefix 14 and 15 escapes occur).
//   * Coverage: every defined coeff_token entry of the bench's own table copy (tb_h264_cavlc_ref_tab.svh, generated by
//     h264_gen_cavlc_tables.py as a separate file from the RTL package; the two agree because both come from OpenH264's
//     encoder tables, cross-checked with JM) must have been exercised.
//   * +INJECT_FAILURE is the negative control (forces one failed check).
// Language: SystemVerilog-2012 (simulation only).
// Revision: 11-09-2026
//   * 11-09-2026: initial version.
// Clocks: clk, 100 MHz.
// -----------------------------------------------------------------------------
`timescale 1ns / 1ps

module tb_rtlnet_h264_cavlc;

  import rtlnet_tb_pkg::*;

  `include "tb_h264_cavlc_ref_tab.svh"
  `include "tb_h264_cavlc_ref.svh"

  logic         clk = 1'b0;
  logic         resetn = 1'b0;
  logic         start = 1'b0;
  logic [1:0]   mode = '0;
  logic [4:0]   nc = '0;
  logic [191:0] coef = '0;
  logic         busy, done;
  logic [4:0]   total_coeff;
  logic         cmd_valid;
  logic         cmd_ready = 1'b0;
  logic [31:0]  cmd_val;
  logic [5:0]   cmd_len;

  always #5 clk = ~clk;

  rtlnet_h264_cavlc_blk dut (
    .clk(clk), .resetn(resetn), .start(start), .mode(mode), .nc(nc), .coef(coef), .busy(busy), .done(done),
    .total_coeff(total_coeff), .cmd_valid(cmd_valid), .cmd_ready(cmd_ready), .cmd_val(cmd_val), .cmd_len(cmd_len)
  );

  int blocks_run = 0;
  int clk_empty_min = 100000, clk_empty_max = 0, clk_dense_max = 0, clk_sparse_max = 0;
  longint unsigned bits_total = 0;

  // Run one block through the DUT and compare with the reference.
  task automatic run_one(input int md, input int ncv, input int c[16], input int pct);
    bitq_t   expq, got;
    int      maxc, cls, tcr, t, nreq;
    bit      fin;
    logic [191:0] cf;
    maxc = (md == 0) ? 16 : ((md == 1) ? 15 : 4);
    cls  = ref_cls(maxc, ncv);
    tcr  = ref_block(expq, maxc, cls, c);
    for (int i = 0; i < 16; i++) cf[12*i +: 12] = 12'(c[i]);
    @(negedge clk);
    start = 1'b1; mode = 2'(md); nc = 5'(ncv); coef = cf;
    @(negedge clk);
    start = 1'b0;
    fin = 0;
    t = 0;
    nreq = 0;
    while (!fin && t < 5000) begin
      cmd_ready = (pct >= 100) ? 1'b1 : (($urandom_range(0, 99) < pct) ? 1'b1 : 1'b0);
      if (cmd_valid && cmd_ready) put_bits(got, cmd_val, int'(cmd_len));
      if (done) begin
        fin = 1;
        tb_check(int'(total_coeff) == tcr, $sformatf("total_coeff %0d, expected %0d (mode %0d nc %0d)", total_coeff, tcr, md, ncv));
      end else begin
        @(negedge clk);
      end
      t++;
      nreq++;
    end
    cmd_ready = 1'b0;
    tb_check(fin, $sformatf("block did not finish (mode %0d nc %0d tc %0d)", md, ncv, tcr));
    tb_check(got == expq, $sformatf("bit string mismatch (mode %0d nc %0d tc %0d): got %0d bits, expected %0d bits", md, ncv, tcr,
                                   got.size(), expq.size()));
    blocks_run++;
    bits_total += expq.size();
    if (pct >= 100) begin
      if (tcr == 0) begin
        if (t < clk_empty_min) clk_empty_min = t;
        if (t > clk_empty_max) clk_empty_max = t;
      end else if (tcr <= 3) begin
        if (t > clk_sparse_max) clk_sparse_max = t;
      end
      if (tcr == maxc && t > clk_dense_max) clk_dense_max = t;
    end
    @(negedge clk);
  endtask

  function automatic int rand_mag(input int mc);
    int bits;
    case (mc)
      0: return $urandom_range(1, 3);
      1: return $urandom_range(1, 30);
      default: begin
        bits = $urandom_range(1, 11);
        return 1 + ($urandom_range(0, (1 << bits) - 1) % 2047);
      end
    endcase
  endfunction

  function automatic int rand_signed(input int mag);
    return ($urandom_range(0, 1) == 1) ? -mag : mag;
  endfunction

  // Block with TotalCoeff tc, TrailingOnes t1 and total_zeros tz (top coefficient at tz + tc - 1).
  task automatic gen_blk(input int maxc, input int tc, input int t1, input int tz, input int mc, output int c[16]);
    int pos [16];
    int top, n, j, k, tmp, cnt;
    int avail [16];
    for (int i = 0; i < 16; i++) c[i] = (i >= maxc) ? rand_signed($urandom_range(1, 2047)) : 0;
    if (tc > 0) begin
      top = tz + tc - 1;
      pos[0] = top;
      for (int i = 0; i < top; i++) avail[i] = i;
      n = top;
      for (int i = 1; i < tc; i++) begin
        k = $urandom_range(0, n - 1);
        pos[i] = avail[k];
        avail[k] = avail[n - 1];
        n--;
      end
      // pos[] holds the positions; sort descending (insertion sort).
      for (int a = 1; a < tc; a++) begin
        tmp = pos[a];
        j = a - 1;
        while ((j >= 0) && (pos[j] < tmp)) begin
          pos[j + 1] = pos[j];
          j--;
        end
        pos[j + 1] = tmp;
      end
      cnt = 0;
      for (int a = 0; a < tc; a++) begin
        if (a < t1)                         c[pos[a]] = rand_signed(1);
        else if ((a == t1) && (t1 < 3))     c[pos[a]] = rand_signed(2 + (rand_mag(mc) % 2046));
        else                                c[pos[a]] = rand_signed(rand_mag(mc));
        cnt++;
      end
    end
  endtask

  function automatic int nc_of_cls(input int cls);
    case (cls)
      0: return $urandom_range(0, 1);
      1: return $urandom_range(2, 3);
      2: return $urandom_range(4, 7);
      default: return $urandom_range(8, 16);
    endcase
  endfunction

  function automatic int pct_rand();
    int r;
    r = $urandom_range(0, 3);
    if (r == 0) return 50;
    if (r == 1) return 20;
    return 100;
  endfunction

  int cb[16];
  int maxc_v, ncls, ncv, tzmax, tzv, nmodes;
  int covered, expected_entries;
  int lvl;

  initial begin
    resetn = 1'b0;
    repeat (6) @(negedge clk);
    resetn = 1'b1;
    repeat (3) @(negedge clk);

    // Directed: every (class, TotalCoeff, TrailingOnes) for the three block kinds.
    for (int md = 0; md < 3; md++) begin
      maxc_v = (md == 0) ? 16 : ((md == 1) ? 15 : 4);
      ncls   = (md == 2) ? 1 : 4;
      for (int cl = 0; cl < ncls; cl++) begin
        for (int tc = 0; tc <= maxc_v; tc++) begin
          for (int t1 = 0; t1 <= ((tc < 3) ? tc : 3); t1++) begin
            for (int rep = 0; rep < 2; rep++) begin
              tzmax = maxc_v - tc;
              tzv   = $urandom_range(0, tzmax);
              gen_blk(maxc_v, tc, t1, tzv, rep + 1, cb);
              ncv = nc_of_cls(cl);
              run_one(md, ncv, cb, pct_rand());
            end
          end
        end
      end
    end

    // Directed: every (TotalCoeff, total_zeros) pair, three placements each.
    for (int md = 0; md < 3; md++) begin
      maxc_v = (md == 0) ? 16 : ((md == 1) ? 15 : 4);
      for (int tc = 1; tc < maxc_v; tc++) begin
        for (int z = 0; z <= maxc_v - tc; z++) begin
          for (int rep = 0; rep < 3; rep++) begin
            gen_blk(maxc_v, tc, $urandom_range(0, (tc < 3) ? tc : 3), z, 1, cb);
            run_one(md, nc_of_cls($urandom_range(0, 3)), cb, pct_rand());
          end
        end
      end
    end

    // Directed: every (zerosLeft, run_before) of the first run: two coefficients, the low one at zl - run.
    for (int md = 0; md < 2; md++) begin
      for (int zl = 1; zl <= 14; zl++) begin
        for (int run = 0; run <= zl; run++) begin
          for (int i = 0; i < 16; i++) cb[i] = 0;
          if ((zl - run) + run + 1 < ((md == 0) ? 16 : 15)) begin
            cb[zl - run] = rand_signed($urandom_range(1, 4));
            cb[zl + 1]   = rand_signed($urandom_range(1, 4));
            run_one(md, nc_of_cls($urandom_range(0, 3)), cb, 100);
          end
        end
      end
    end

    // Directed: each single level from -2047 to +2047, and as the highest level of an 11-coefficient block.
    for (lvl = -2047; lvl <= 2047; lvl++) begin
      if (lvl != 0) begin
        for (int i = 0; i < 16; i++) cb[i] = 0;
        cb[$urandom_range(0, 14)] = lvl;
        run_one(0, nc_of_cls($urandom_range(0, 3)), cb, 100);
        if ((lvl > 1) || (lvl < -1)) begin
          if (($urandom_range(0, 7)) == 0) begin
            gen_blk(16, 11, 0, 0, 1, cb);
            cb[10] = lvl;
            run_one(0, nc_of_cls($urandom_range(0, 3)), cb, 100);
          end
        end
      end
    end

    // Random blocks of random density and magnitude.
    for (int n = 0; n < 6000; n++) begin
      nmodes = $urandom_range(0, 2);
      maxc_v = (nmodes == 0) ? 16 : ((nmodes == 1) ? 15 : 4);
      for (int i = 0; i < 16; i++) cb[i] = 0;
      for (int i = 0; i < 16; i++) begin
        if ($urandom_range(0, 15) < ((n % 16) + 1)) cb[i] = rand_signed(rand_mag($urandom_range(0, 2)));
      end
      run_one(nmodes, $urandom_range(0, 16), cb, pct_rand());
    end

    // Coverage of the coeff_token table.
    covered = 0;
    expected_entries = 0;
    for (int cl = 0; cl < 5; cl++) begin
      for (int tc = 0; tc <= 16; tc++) begin
        for (int t1 = 0; t1 < 4; t1++) begin
          if (REF_CT_LEN[cl][tc][t1] != 0) begin
            expected_entries++;
            if (ref_hit_ct[cl][tc][t1] > 0) covered++;
            else $display("NOT COVERED: ct cls %0d tc %0d t1 %0d", cl, tc, t1);
          end
        end
      end
    end
    tb_check(covered == expected_entries, $sformatf("coeff_token coverage %0d of %0d", covered, expected_entries));
    $display("STAT blocks=%0d bits=%0d coeff_token_entries_covered=%0d/%0d", blocks_run, bits_total, covered, expected_entries);
    $display("STAT clocks start-to-done (no stall): empty block min %0d max %0d, tc<=3 max %0d, full block max %0d",
             clk_empty_min, clk_empty_max, clk_sparse_max, clk_dense_max);
    tb_verdict("tb_rtlnet_h264_cavlc");
  end

  // Watchdog.
  initial begin
    #2000000000;
    tb_error("watchdog");
    tb_verdict("tb_rtlnet_h264_cavlc");
  end

endmodule
