"""Purpose: generate the plain-Verilog IP Integrator boundary (hdl/rtlnet_zybo_video_bd.v) of rtlnet_zybo_video.sv without hand-copied ports.
Overview: IP Integrator takes a module reference only from a plain Verilog file; this script writes that file from the parameter and port
  list of the SystemVerilog wrapper, preserving the interface attributes and connecting every parameter and port by name.
Usage: python rtlnet_generate_video_wrapper.py            (write hdl/rtlnet_zybo_video_bd.v)
       python rtlnet_generate_video_wrapper.py --check    (fail when the committed boundary differs from the generated text)
Revision: 11-15-2026.
"""
from pathlib import Path
import re
import sys


def render(board, module='rtlnet_zybo_video', generator='rtlnet_generate_video_wrapper.py'):
    text = (board / 'hdl/rtlnet_zybo_video.sv').read_text(encoding='utf-8')
    header = text[text.index('module ' + module + ' #('):text.index('\n);') + 3]
    declarations = re.sub(r'//[^\n]*|/\*.*?\*/', '', header, flags=re.S)
    params = re.findall(r'parameter\s+(?:bit|int)\s+(\w+)\s*=', declarations)
    ports = re.findall(r'\b(?:input|output)\s+logic\s+(?:\[[^]]+\]\s+)?(\w+)', declarations)
    assert params and ports and len(set(ports)) == len(ports)
    # String parameters are bench-only switches: the boundary does not expose them (its instance keeps their defaults).
    strings = len(re.findall(r'\bparameter\s+string\b', declarations))
    assert len(params) + strings == len(re.findall(r'\bparameter\b', declarations)), 'Review new parameter syntax'
    assert len(ports) == len(re.findall(r'\b(?:input|output|inout)\b', declarations)), 'Review new port syntax'
    header = header.replace('module ' + module + ' #(', 'module ' + module + '_bd #(')
    header = re.sub(r'[ \t]*parameter string[^\n]*\n', '', header)
    header = re.sub(r'parameter bit\s+', 'parameter ', header)
    header = re.sub(r'parameter int\s+', 'parameter integer ', header)
    header = re.sub(r'\b(input|output) logic\b', r'\1 wire', header)
    return ('// Purpose: plain Verilog module-reference boundary for IP Integrator.\n'
            '// Overview: generated by ' + generator + '; no logic or timing change.\n'
            '// Revision: 11-15-2026.\n' + header + '\n\n  ' + module + ' #(\n' +
            ',\n'.join(f'    .{name}({name})' for name in params) + '\n  ) u_rtl (\n' +
            ',\n'.join(f'    .{name}({name})' for name in ports) + '\n  );\nendmodule\n')


def check(board):
    target = board / 'hdl/rtlnet_zybo_video_bd.v'
    if target.read_text(encoding='utf-8') != render(board):
        raise ValueError('Verilog wrapper is stale; run rtlnet_generate_video_wrapper.py')


if __name__ == '__main__':
    board = Path(__file__).resolve().parents[1]
    if '--check' in sys.argv:
        check(board)
    else:
        (board / 'hdl/rtlnet_zybo_video_bd.v').write_text(render(board), encoding='utf-8', newline='\n')
    print('RTLNET_VIDEO_WRAPPER: PASS plain Verilog boundary; all parameters, attributes and ports preserved')
