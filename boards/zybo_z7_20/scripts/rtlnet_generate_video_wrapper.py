"""Purpose: maintain the plain-Verilog IP Integrator boundary without hand-copied ports.
Overview: preserve interface attributes and connect every parameter/port by name.
Revision: 11-14-2026.
"""
from pathlib import Path
import re
import sys


def render(board):
    text = (board / 'hdl/rtlnet_zybo_video.sv').read_text(encoding='utf-8')
    header = text[text.index('module rtlnet_zybo_video #('):text.index('\n);') + 3]
    declarations = re.sub(r'//[^\n]*|/\*.*?\*/', '', header, flags=re.S)
    params = re.findall(r'parameter\s+(?:bit|int)\s+(\w+)\s*=', declarations)
    ports = re.findall(r'\b(?:input|output)\s+logic\s+(?:\[[^]]+\]\s+)?(\w+)', declarations)
    assert params and ports and len(set(ports)) == len(ports)
    assert len(params) == len(re.findall(r'\bparameter\b', declarations)), 'Review new parameter syntax'
    assert len(ports) == len(re.findall(r'\b(?:input|output|inout)\b', declarations)), 'Review new port syntax'
    header = header.replace('module rtlnet_zybo_video #(', 'module rtlnet_zybo_video_bd #(')
    header = re.sub(r'parameter bit\s+', 'parameter ', header)
    header = re.sub(r'parameter int\s+', 'parameter integer ', header)
    header = re.sub(r'\b(input|output) logic\b', r'\1 wire', header)
    return ('// Purpose: plain Verilog module-reference boundary for IP Integrator.\n'
            '// Overview: generated by rtlnet_generate_video_wrapper.py; no logic or timing change.\n'
            '// Revision: 11-14-2026.\n' + header + '\n\n  rtlnet_zybo_video #(\n' +
            ',\n'.join(f'    .{name}({name})' for name in params) + '\n  ) u_rtl (\n' +
            ',\n'.join(f'    .{name}({name})' for name in ports) + '\n  );\nendmodule\n')


def check(board):
    target = board / 'hdl/rtlnet_zybo_video_bd.v'
    if target.read_text(encoding='utf-8') != render(board):
        raise ValueError('Verilog wrapper is stale; run rtlnet_generate_video_wrapper.py')


if __name__ == '__main__':
    board = Path(__file__).resolve().parents[1]
    if '--check' in sys.argv:
        check(board)
    else:
        (board / 'hdl/rtlnet_zybo_video_bd.v').write_text(render(board), encoding='utf-8')
    print('RTLNET_VIDEO_WRAPPER: PASS plain Verilog boundary; all parameters, attributes and ports preserved')
